// The CCSDS bit stream is big-endian (most significant bit first) on every platform. SpAec stored
// and loaded words with an unconditional byte swap, which is only right on little-endian
// machines: on big-endian ones (s390x, POWER) the encoded bytes were reordered and correct
// streams were decoded to wrong values without an error. The expected bytes are reference streams.
#include <cstdint>
#include <iostream>
#include <vector>

#include "spaec/detail/encoder/EncoderSeq.h"
#include "spaec/detail/decoder/DecoderSeq.h"

using namespace spaec::detail;

// Zero blocks, small values (second extension, split sample with small k), values around the
// middle of the range (split sample), pseudo-random values (no compression), a partial block
static std::vector<uint32_t> input(uint32_t bpv)
{
    std::vector<uint32_t> v;
    const uint32_t maxv = bpv == 32 ? 0xffffffffu : ((1u << bpv) - 1);
    uint32_t x = 12345;
    for (int32_t i = 0; i < 64; i++)
        v.push_back(0);
    for (int32_t i = 0; i < 64; i++)
        v.push_back(7 + (i % 3));
    for (int32_t i = 0; i < 64; i++)
        v.push_back((maxv / 2) + ((i * 37) % 200) - 100);
    for (int32_t i = 0; i < 64; i++) {
        x = x * 1103515245u + 12345u;
        v.push_back(x & maxv);
    }
    for (int32_t i = 0; i < 37; i++)
        v.push_back((i * 977u) & maxv);
    return v;
}

struct Expected
{
    uint32_t bpv;
    std::vector<uint8_t> bytes;  // block size 16, reference sample interval 8, preprocessed
};

template <typename T>
static int32_t check(const Expected& e)
{
    const std::vector<uint32_t> in32 = input(e.bpv);
    std::vector<T> values(in32.begin(), in32.end());
    int32_t failures = 0;

    encoder::EncoderSeq<T, T> encoder(static_cast<uint8_t>(e.bpv), 16, 8, CodeOptionSet::Basic);
    std::vector<uint8_t> encoded(values.size() * 5 + 64, 0);
    const size_t length = encoder.encode(Span<T>(values), Span<uint8_t>(encoded));
    encoded.resize(length);
    if (encoded != e.bytes) {
        size_t i = 0;
        while (i < length && i < e.bytes.size() && encoded[i] == e.bytes[i])
            ++i;
        std::cerr << "bpv " << e.bpv << ": encoded bytes differ from the reference stream at byte " << i << " (length " << length << ", reference " << e.bytes.size() << ")\n";
        ++failures;
    }

    DecoderSeq<T, T> decoder(static_cast<uint8_t>(e.bpv), 16, 8, CodeOptionSet::Basic);
    std::vector<T> decoded(values.size());
    std::vector<uint8_t> stream = e.bytes;
    try {
        decoder.decode(Span<uint8_t>(stream), Span<T>(decoded));
        if (decoded != values) {
            std::cerr << "bpv " << e.bpv << ": reference stream decoded to wrong values\n";
            ++failures;
        }
    }
    catch (const std::exception& ex) {
        std::cerr << "bpv " << e.bpv << ": decoding the reference stream failed: " << ex.what() << '\n';
        ++failures;
    }
    return failures;
}

